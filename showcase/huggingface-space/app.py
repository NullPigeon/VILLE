MODEL = os.getenv("HF_MODEL", "Qwen/Qwen3-4B-Instruct-2507")
CSS = Path(__file__).with_name("style.css").read_text(encoding="utf-8")


def complete(system: str, brief: str) -> str:
    token = os.getenv("HF_TOKEN", "").strip()
    if not token:
        raise ValueError("Space owner: add HF_TOKEN as a secret to enable the live demo.")
    answer = InferenceClient(provider="auto", api_key=token).chat.completions.create(
        model=MODEL,
        messages=[{"role": "system", "content": system}, {"role": "user", "content": brief}],
        max_tokens=450,
        temperature=0.2,
    )
    return answer.choices[0].message.content or ""


def ask_agent(brief: str):
    try:
        result = run_agent(brief, complete)
    except ValueError as exc:
        raise gr.Error(str(exc)) from exc
    except Exception as exc:
        # Public Spaces should not reveal provider errors, headers or secrets.
        raise gr.Error("The model is unavailable right now. Please try again later.") from exc

    service_id = result["service_id"]
    name = SERVICES[service_id][0]
    route = (
        f"### {escape(name)}\n\n{escape(result['reason'])}\n\n"
        f"[Open this service in LANDVILLE Market ↗]({market_url(service_id)})\n\n"
        "*The Market checks live availability and price before wallet approval.*"
    )
    first = (
        f"{escape(result['first_step'])}\n\n"
        "*Generated by a Hugging Face model. No live service or payment was used here.*"
    )
    return route, first


def ask_scrapy_to_build(idea: str, district: str):
    try:
        spec = run_builder(idea, district, complete)
        preview = render_building(spec, district)
    except ValueError as exc:
        raise gr.Error(str(exc)) from exc
    except Exception as exc:
        raise gr.Error("Scrapy's demo model is unavailable right now. Please try again later.") from exc
    features = "\n".join(f"- {escape(item)}" for item in spec["features"])
    plan = (
        f"### {escape(spec['title'])}\n"
        f"**{escape(district)} · {escape(spec['kind'].title())} concept**\n\n"
        f"{escape(spec['purpose'])}\n\n**Inside this place**\n{features}\n\n"
        f"> {escape(spec['scrapy_line'])}\n\n"
        "**This is a concept preview.** No proposal, vote, executable building or World object was created. "
        "To build for real, [take the idea to Scrapy in LANDVILLE](https://landville.xyz/chat?room=BUILD)."
    )
    return preview, plan


